"""Generate the Results section of README.md from results/metrics.json and results/cv_results.csv.

Usage: python scripts/make_readme.py
Everything between the RESULTS markers is overwritten; nothing else in README.md is touched.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
METRICS = ROOT / "results" / "metrics.json"
CV = ROOT / "results" / "cv_results.csv"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
CV_METRICS = [("precision", "Precision"), ("recall", "Recall"), ("f1", "F1"), ("average_precision", "PR-AUC")]
TEST_METRICS = [("accuracy", "Accuracy"), ("precision", "Precision"), ("recall", "Recall"),
                ("f1", "F1"), ("average_precision", "PR-AUC")]


def f4(x):
    return f"{float(x):.4f}"


def load():
    metrics = json.loads(METRICS.read_text(encoding="utf-8"))
    with open(CV, newline="", encoding="utf-8") as f:
        cv = sorted(csv.DictReader(f), key=lambda r: float(r["average_precision_mean"]), reverse=True)
    return metrics, cv


def render(metrics, cv):
    rows, cc, split = metrics["rows"], metrics["class_counts"], metrics["split"]
    total = cc["ham"] + cc["spam"]
    thr, sel = metrics["threshold"], metrics["selected_model"]
    out = [
        "_Generated by `scripts/make_readme.py` from `results/metrics.json` and `results/cv_results.csv`. "
        "Do not edit by hand._",
        "",
        "### Dataset",
        "",
        "| | Rows |",
        "|---|---|",
        f"| Raw rows | {rows['raw']} |",
        f"| Rows whose text was split across extra CSV columns (rebuilt) | {rows['rows_with_split_text_rebuilt']} |",
        f"| Rows after the column fix | {rows['after_column_fix']} |",
        f"| Duplicates removed | {rows['duplicates_removed']} |",
        f"| Final rows | {rows['final']} |",
        f"| ham | {cc['ham']} ({cc['ham'] / total * 100:.2f}%) |",
        f"| spam | {cc['spam']} ({cc['spam'] / total * 100:.2f}%) |",
        f"| Train / test | {split['train']} / {split['test']} (test_size={split['test_size']}, stratified) |",
        "",
        f"Settings: random_state={metrics['random_state']}, TF-IDF max_features={sel['tfidf_max_features']}, "
        f"preprocessing variant `{metrics['preprocessing']['chosen']}`.",
        "",
        f"### Cross-validation ({metrics['cv']['n_splits']}-fold stratified, training set only, mean ± std)",
        "",
        "| Model | " + " | ".join(name for _, name in CV_METRICS) + " |",
        "|---|" + "---|" * len(CV_METRICS),
    ]
    for r in cv:
        cells = [f"{f4(r[m + '_mean'])} ± {f4(r[m + '_std'])}" for m, _ in CV_METRICS]
        out.append(f"| {r['model']} | " + " | ".join(cells) + " |")
    pre = metrics["preprocessing"]["cv_average_precision"]
    out += [
        "",
        "Stopword experiment (selected model, mean CV PR-AUC): "
        + ", ".join(f"`{k}` {f4(v['mean'])} ± {f4(v['std'])}" for k, v in pre.items()) + ".",
        "",
        "### Selected model",
        "",
        f"- Rule (fixed before results): {metrics['selection_rule']}.",
        f"- Selected: **{sel['name']}** (`{sel['class']}`).",
        f"- Threshold on `{thr['score_method']}`: default {thr['default']}, tuned {thr['tuned']} "
        + ("(lowest out-of-fold threshold with precision ≥ " + str(thr['target_oof_precision']) + ")."
           if thr["tuning_succeeded"] else "(no threshold reached the target precision; default used)."),
        "",
        "### Held-out test set (evaluated once)",
        "",
        "| Threshold | " + " | ".join(name for _, name in TEST_METRICS) + " | TN | FP | FN | TP |",
        "|---|" + "---|" * (len(TEST_METRICS) + 4),
    ]
    for key, label in [("default_threshold", "default"), ("tuned_threshold", "tuned")]:
        t = metrics["test_metrics"][key]
        cm = t["confusion_matrix"]
        out.append(f"| {label} | " + " | ".join(f4(t[m]) for m, _ in TEST_METRICS)
                   + f" | {cm['tn']} | {cm['fp']} | {cm['fn']} | {cm['tp']} |")
    return "\n".join(out)


def splice(readme, block):
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{block}\n{END}{tail}"


if __name__ == "__main__":
    README.write_text(splice(README.read_text(encoding="utf-8"), render(*load())), encoding="utf-8")
    print(f"Wrote results section to {README.name}")
